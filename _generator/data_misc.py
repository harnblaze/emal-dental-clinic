def photo(key_or_id, w, h=None, faces=False, q=80, crop=""):
    """crop — свои параметры кадрирования imgix, например фокус и зум на лице."""
    pid = PHOTOS.get(key_or_id, key_or_id)
    url = f"{UNSPLASH}{pid}?auto=format&fit=crop&w={w}&q={q}"
    if h:
        url += f"&h={h}"
    if crop:
        url += crop
    elif faces:
        url += "&crop=faces"
    return url


